#!/usr/bin/env bash
# Writes docs/RUNS.md from the evidence bundles in deployments/runs: every
# recorded job, each submission's result, how long it took from submit to
# settled, and the transactions that carried each signed result.
#   scripts/runs-doc.sh            write docs/RUNS.md
#   scripts/runs-doc.sh --check    fail if docs/RUNS.md is out of date
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
OUT="$ROOT/docs/RUNS.md"

render() {
  echo "# Recorded runs"
  echo
  echo "Generated by \`scripts/runs-doc.sh\` from \`deployments/runs/*.json\`; do not edit by hand."
  echo
  echo "Each row is one submission. Seconds run from the submit transaction to the contract settling it: grading in the enclave, the signed result posted, and on contracts with the on-chain proof check, Intel's quote checked first. Check any row with \`sphinx verify deployments/runs/<file>\` (offline) or \`--online\` (re-read from chain)."
  echo
  echo "| Record | Network | Job | Agent | Result | Outcome | Seconds | Proof checked on chain | Signed result |"
  echo "|---|---|---|---|---|---|---|---|---|"
  for f in "$ROOT"/deployments/runs/*.json; do
    jq -r --arg file "$(basename "$f")" '
      def secs(a; z): if a and z then (((z | tonumber) - (a | tonumber)) / 1e9 * 10 | round / 10 | tostring) else "–" end;
      . as $b
      | (if $b.network == "mainnet" then "https://nearblocks.io/txns" else "https://testnet.nearblocks.io/txns" end) as $ex
      | ($b.job.title // ("job " + $b.job.id)) as $name
      | (if $b.job.assessment then "assessment: " + $name else $name end) as $label
      | ([$b.results[] | select(.kind == "score")]) as $scores
      | $b.submissions[]
      | . as $s
      | ([$scores[] | select((.args.score.sub_id | tostring) == ($s.sub_id | tostring))][0].tx_hash // null) as $tx
      | (if $s.status == "Passed" then (if $b.job.assessment then "badge written" else "paid" end)
         elif $s.status == "Failed" then
           (if $b.job.assessment or $b.job.status == "Paid" then "bond kept"
            elif ($b.job.status | IN("Refunded", "Cancelled", "Rejected")) then "bond returned"
            else "bond held" end)
         else ($s.status | ascii_downcase) end) as $outcome
      | "| [`\($file)`](../deployments/runs/\($file)) | \($b.network) | \($label) | `\($s.agent)` | \($s.passed)/\($s.total) | \($outcome) | \(secs($s.submitted_at_ns; $s.settled_at_ns)) | \(if $b.config.enclave then "yes" else "no" end) | \(if $tx then "[`\($tx[0:10])…`](\($ex)/\($tx))" else "–" end) |"
    ' "$f"
  done
}

if [ "${1:-}" = --check ]; then
  diff -u "$OUT" <(render) >/dev/null || { echo "docs/RUNS.md is out of date: run scripts/runs-doc.sh" >&2; exit 1; }
  echo "docs/RUNS.md is up to date"
else
  render > "$OUT"
  echo "wrote $OUT"
fi
